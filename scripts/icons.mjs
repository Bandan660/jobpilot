/**
 * Every BanApply icon, from one definition.
 *
 * Run with `npm run icons` after changing the mark. Nothing here is edited by
 * hand — the two SVGs it writes are outputs, not sources, and editing one
 * would be undone the next time this runs.
 *
 * WHY ONE SCRIPT ACROSS BOTH WORKSPACES
 *
 * The extension icon and the site favicon drifted apart once: the site's
 * diamond was 44% of its canvas against the extension's 57%. Nobody can name
 * that difference and everybody registers it, because the browser tab and the
 * toolbar button sit two inches apart. Two places to change a shape is what
 * made it possible, so there is one now.
 *
 * WHY THE OUTPUTS ARE NOT ALL THE SAME PICTURE
 *
 * Three platforms want three different shapes, and giving them one file copied
 * five times is how you get black corners on an iPhone and a clipped mark on
 * an Android home screen. Each variant below says what it is for.
 */
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/* ---------------------------------- the mark ------------------------------ */

/** Straight from frontend/src/styles/tokens.css. Not approximations. */
const AMBER = '#FFB020';
const INK = '#080D16';

/**
 * Geometry, in a 128 box, measured from the approved artwork: the diamond is
 * 56.9% of the canvas wide and 74.4% tall, centred, on a square with a 16.8%
 * corner radius.
 */
const BOX = 128;
const RADIUS = 21.5;
const HALF_W = 36.4;
const HALF_H = 47.6;

const diamond = (halfW = HALF_W, halfH = HALF_H) => {
  const c = BOX / 2;
  return `M${c} ${c - halfH} L${c + halfW} ${c} L${c} ${c + halfH} L${c - halfW} ${c} Z`;
};

const svg = (body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${BOX} ${BOX}" width="${BOX}" height="${BOX}">\n  ${body}\n</svg>\n`;

/** Rounded square, transparent outside the corners. Browser tabs, Android "any". */
const ROUNDED = svg(
  `<rect width="${BOX}" height="${BOX}" rx="${RADIUS}" fill="${INK}"/>\n  <path d="${diamond()}" fill="${AMBER}"/>`
);

/**
 * Full bleed, square corners.
 *
 * iOS applies its own squircle and does not honour transparency: a rounded PNG
 * there renders as our corners with black outside them, inside Apple's
 * rounding. Corners inside corners.
 */
const FULL_BLEED = svg(
  `<rect width="${BOX}" height="${BOX}" fill="${INK}"/>\n  <path d="${diamond()}" fill="${AMBER}"/>`
);

/**
 * Full bleed with a smaller mark.
 *
 * A launcher may crop a maskable icon to any shape, so everything that must
 * survive sits inside the central 80% — a circle of radius 40% of the canvas.
 * The full-size diamond's tips reach 37.2%, which fits and leaves no margin
 * worth defending on someone's home screen.
 */
const MASKABLE = svg(
  `<rect width="${BOX}" height="${BOX}" fill="${INK}"/>\n  <path d="${diamond(22.6, 29.5)}" fill="${AMBER}"/>`
);

/* --------------------------------- outputs -------------------------------- */

const HEADER = (what) =>
  `<!--\n  Generated by scripts/icons.mjs — run \`npm run icons\` rather than editing.\n  ${what}\n-->\n`;

const svgFiles = [
  [
    'extension/icons/icon.svg',
    HEADER('The mark itself. Every raster below is rendered from this geometry.') + ROUNDED,
  ],
  [
    'frontend/public/favicon.svg',
    HEADER('Browser tab. Same geometry as the extension icon, by construction.') + ROUNDED,
  ],
];

/**
 * Rendered from the vector at every size, never downscaled from a larger PNG:
 * a 16px icon reduced from 128 is mush, and one rendered from the geometry is
 * not.
 */
const pngFiles = [
  ['extension/icons/icon16.png', ROUNDED, 16, false],
  ['extension/icons/icon32.png', ROUNDED, 32, false],
  ['extension/icons/icon48.png', ROUNDED, 48, false],
  ['extension/icons/icon128.png', ROUNDED, 128, false],
  ['frontend/public/icon-192.png', ROUNDED, 192, false],
  ['frontend/public/icon-512.png', ROUNDED, 512, false],
  // Flattened: every pixel is opaque anyway, and an alpha channel iOS treats
  // as black is not worth carrying for nothing.
  ['frontend/public/apple-touch-icon.png', FULL_BLEED, 180, true],
  ['frontend/public/icon-maskable-512.png', MASKABLE, 512, false],
];

for (const [path, contents] of svgFiles) {
  await writeFile(resolve(root, path), contents);
  console.log(`${path.padEnd(38)} vector`);
}

for (const [path, source, size, flatten] of pngFiles) {
  let pipeline = sharp(Buffer.from(source), { density: 1200 }).resize(size, size);
  if (flatten) pipeline = pipeline.flatten({ background: INK });

  await pipeline.png({ compressionLevel: 9 }).toFile(resolve(root, path));
  console.log(`${path.padEnd(38)} ${size}x${size}${flatten ? ' opaque' : ''}`);
}

console.log('\nCheck the 16px still reads before shipping — it is the only size that argues.');
